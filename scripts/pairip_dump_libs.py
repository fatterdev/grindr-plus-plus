#!/usr/bin/env python3
"""Dump in-memory RX of every lib mapped from a split APK and diff vs on-disk.

PairIP decrypts selected `.text` regions in place at load time. The on-disk
split keeps the ciphertext, so a decrypt pack must carry the in-memory image.
This tool:

  1. force-stops + launches the package,
  2. waits for the pid,
  3. after a configurable delay dumps every `r-xp` map of the split APK
     (`/proc/<pid>/mem`, 4 KiB pages) in one on-device shell script,
  4. repeats the pass a moment later (short-lived processes),
  5. reassembles each map at its real `.so` file offset and diffs vs disk.

Only libs whose memory image differs from disk are written as `<lib>.mem.bin`
(the decrypted image), plus a `report.json` with ranges and hashes.

Usage:
  python scripts/pairip_dump_libs.py --version-code 194910 \
      --split tmp/split_config.arm64_v8a.apk --out tmp/pairip-194910 \
      --launch com.grindrapp.android/.HomeActivityOriginal --delay 1.15
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import struct
import subprocess
import sys
import tempfile
import time
import zipfile
from pathlib import Path

DEFAULT_PKG = "com.grindrapp.android"
REMOTE_DIR = "/data/local/tmp/gpp_dump_libs"
REMOTE_SH = "/data/local/tmp/gpp_dump_libs.sh"

DEVICE_SCRIPT = r"""#!/system/bin/sh
# generated by scripts/pairip_dump_libs.py
APK="$1"; OUT="$2"; ACT="$3"; DELAY="$4"; PKG="$5"
rm -rf "$OUT"; mkdir -p "$OUT"
if [ "$ACT" != "none" ]; then
  am force-stop "$PKG"
  am start -n "$ACT" >/dev/null 2>&1
fi
T0=$(date +%s%N)
find_pid() {
  for q in $(pidof "$PKG" 2>/dev/null); do
    if grep -qF "$APK" /proc/$q/maps 2>/dev/null; then
      echo "$q"
      return 0
    fi
  done
  return 1
}
p=""
i=0
while [ $i -lt 800 ]; do
  p=$(find_pid)
  [ -n "$p" ] && break
  sleep 0.01
  i=$((i+1))
done
if [ -z "$p" ]; then echo "NO_PID" > "$OUT/status.txt"; exit 2; fi
echo "pid=$p" > "$OUT/status.txt"
cat /proc/$p/maps > "$OUT/maps.txt" 2>/dev/null
grep -F "$APK" "$OUT/maps.txt" | grep ' r-xp ' > "$OUT/rx_maps.txt"
dump_pass() {
  pass=$1
  cat /proc/$p/maps > "$OUT/maps_p$pass.txt" 2>/dev/null || return 0
  grep -F "$APK" "$OUT/maps_p$pass.txt" | grep ' r-xp ' > "$OUT/rx_p$pass.txt"
  : > "$OUT/manifest_p$pass.txt"
  n=0
  while read -r line; do
    [ -z "$line" ] && continue
    range=$(echo "$line" | cut -d' ' -f1)
    fo=$(echo "$line" | cut -d' ' -f3)
    a=${range%-*}; b=${range#*-}
    start=$a; end=$b
    # maps are page aligned: drop the low 3 hex digits to get page numbers
    skip=$(printf '%d' 0x${a%???})
    last=$(printf '%d' 0x${b%???})
    count=$((last - skip))
    dd if=/proc/$p/mem bs=4096 skip=$skip count=$count \
       of="$OUT/p${pass}_$n.bin" 2>/dev/null
    echo "$start $end $fo $n" >> "$OUT/manifest_p$pass.txt"
    n=$((n+1))
  done < "$OUT/rx_p$pass.txt"
}
now=$(date +%s%N)
elapsed=$(( (now - T0) / 1000000 ))
want=$(( ${DELAY%.*} * 1000 ))
[ $elapsed -lt $want ] && sleep $(( (want - elapsed) / 1000 ))
pass=1
while [ $pass -le 4 ]; do
  # Always attempt pass 1: gated stock builds can exit between find_pid and
  # the first dump. Subsequent passes still require a live process.
  if [ $pass -gt 1 ] && [ -z "$(pidof "$PKG")" ]; then break; fi
  dump_pass $pass
  pass=$((pass+1))
  sleep 0.15
done
echo "done" >> "$OUT/status.txt"
"""


def adb(serial: str | None, *args: str, check: bool = True) -> str:
    cmd = ["adb"]
    if serial:
        cmd += ["-s", serial]
    cmd += list(args)
    r = subprocess.run(
        cmd, capture_output=True, text=True, encoding="utf-8", errors="replace"
    )
    if check and r.returncode != 0:
        raise RuntimeError(f"adb {' '.join(args)} failed: {r.stderr or r.stdout}")
    return (r.stdout or "") + (r.stderr or "")


def adb_su(serial: str | None, cmd: str, check: bool = True) -> str:
    return adb(serial, "shell", "su", "-c", cmd, check=check)


def sha1(data: bytes) -> str:
    return hashlib.sha1(data).hexdigest()


def zip_stored_offsets(apk: Path) -> dict[str, tuple[int, int]]:
    """name -> (data_offset, uncompressed_size) for STORED entries."""
    out: dict[str, tuple[int, int]] = {}
    with apk.open("rb") as fh:
        with zipfile.ZipFile(apk) as zf:
            for info in zf.infolist():
                if info.compress_type != zipfile.ZIP_STORED:
                    continue
                fh.seek(info.header_offset)
                header = fh.read(30)
                if header[:4] != b"PK\x03\x04":
                    continue
                name_len = struct.unpack_from("<H", header, 26)[0]
                extra_len = struct.unpack_from("<H", header, 28)[0]
                out[info.filename] = (
                    info.header_offset + 30 + name_len + extra_len,
                    info.file_size,
                )
    return out


def elf_rx_file_range(so: bytes) -> tuple[int, int]:
    e_phoff = struct.unpack_from("<Q", so, 32)[0]
    e_phentsize, e_phnum = struct.unpack_from("<HH", so, 54)
    for i in range(e_phnum):
        off = e_phoff + i * e_phentsize
        p_type, p_flags, p_offset, p_vaddr, p_paddr, p_filesz, p_memsz, p_align = (
            struct.unpack_from("<IIQQQQQQ", so, off)
        )
        if p_type == 1 and (p_flags & 1):
            return p_offset, p_filesz
    raise RuntimeError("no RX PT_LOAD")


def diff_ranges(a: bytes, b: bytes) -> list[tuple[int, int]]:
    n = min(len(a), len(b))
    out: list[tuple[int, int]] = []
    start = None
    for i in range(n):
        if a[i] != b[i]:
            if start is None:
                start = i
        elif start is not None:
            out.append((start, i))
            start = None
    if start is not None:
        out.append((start, n))
    return out


def covered_diff_ranges(a: bytes, b: bytes, mask: bytes) -> list[tuple[int, int]]:
    """Diff ranges restricted to bytes whose mask byte is non-zero."""
    n = min(len(a), len(b), len(mask))
    out: list[tuple[int, int]] = []
    start = None
    for i in range(n):
        if mask[i] and a[i] != b[i]:
            if start is None:
                start = i
        elif start is not None:
            out.append((start, i))
            start = None
    if start is not None:
        out.append((start, n))
    return out


def count_covered_diff(a: bytes, b: bytes, mask: bytes) -> int:
    return sum(e - s for s, e in covered_diff_ranges(a, b, mask))


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--package", default=DEFAULT_PKG)
    ap.add_argument("--version-code", type=int, required=True)
    ap.add_argument("--split", type=Path, required=True, help="on-disk split APK")
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--launch", default="", help="component to launch")
    ap.add_argument("--delay", default="1.15", help="seconds after pid before pass 1")
    ap.add_argument("--serial", default=None)
    ap.add_argument("--no-launch", action="store_true", help="dump a running process")
    ap.add_argument("--keep-remote", action="store_true")
    args = ap.parse_args()

    args.out.mkdir(parents=True, exist_ok=True)
    split_apk = args.split.resolve()
    offsets = zip_stored_offsets(split_apk)
    libs = {
        Path(name).name: (name, off, size)
        for name, (off, size) in offsets.items()
        if name.startswith("lib/") and name.endswith(".so")
    }
    print(f"split={split_apk.name} stored libs={len(libs)}")

    device_split = None
    paths = adb(args.serial, "shell", "pm", "path", args.package)
    for line in paths.splitlines():
        p = line.strip().removeprefix("package:")
        if "arm64" in p:
            device_split = p
    if not device_split:
        raise SystemExit("no arm64 split path from pm path")
    print(f"device split={device_split}")

    script_local = Path(tempfile.gettempdir()) / "gpp_dump_libs.sh"
    script_local.write_text(DEVICE_SCRIPT, encoding="utf-8", newline="\n")
    adb(args.serial, "push", str(script_local), REMOTE_SH)
    adb_su(args.serial, f"chmod 755 {REMOTE_SH}")

    if args.no_launch:
        cmd = (
            f"sh {REMOTE_SH} {device_split} {REMOTE_DIR} {args.launch or 'none'} "
            f"0 {args.package}"
        )
    else:
        cmd = (
            f"sh {REMOTE_SH} {device_split} {REMOTE_DIR} {args.launch} "
            f"{args.delay} {args.package}"
        )
    print("running device dump…")
    t0 = time.time()
    adb_su(args.serial, cmd, check=False)
    print(f"device dump returned after {time.time() - t0:.2f}s")

    local_raw = args.out / "raw"
    if local_raw.exists():
        import shutil

        shutil.rmtree(local_raw)
    local_raw.mkdir(parents=True, exist_ok=True)
    adb(args.serial, "pull", f"{REMOTE_DIR}/.", str(local_raw))
    if not args.keep_remote:
        adb_su(args.serial, f"rm -rf {REMOTE_DIR} {REMOTE_SH}", check=False)

    status = local_raw / "status.txt"
    print(
        "status:",
        status.read_text(encoding="utf-8", errors="replace").strip()
        if status.is_file()
        else "missing",
    )

    manifests: dict[int, list[tuple[int, int, int, int]]] = {}
    for mf in sorted(local_raw.glob("manifest_p*.txt")):
        pass_no = int(re.sub(r"\D", "", mf.stem) or "0")
        rows = []
        for line in mf.read_text(encoding="utf-8", errors="replace").splitlines():
            parts = line.split()
            if len(parts) != 4:
                continue
            start_s, end_s, fo_s, idx = parts
            rows.append((int(start_s, 16), int(end_s, 16), int(fo_s, 16), int(idx)))
        manifests[pass_no] = rows

    report: dict = {
        "package": args.package,
        "versionCode": args.version_code,
        "split": str(split_apk),
        "splitSha1": sha1(split_apk.read_bytes()),
        "passes": {},
        "libs": {},
    }

    # group maps by lib using zip entry offsets
    def lib_for(fo: int) -> tuple[str, int] | None:
        for name, (entry_name, off, size) in libs.items():
            if off <= fo < off + size:
                return name, fo - off
        return None

    best: dict[str, tuple[int, bytearray, int]] = {}
    masks: dict[str, bytes] = {}
    for pass_no, rows in manifests.items():
        covered: dict[str, bytearray] = {}
        mask: dict[str, bytearray] = {}
        diffs: dict[str, int] = {}
        for start, end, fo, idx in rows:
            hit = lib_for(fo)
            if not hit:
                continue
            lib, mem_off = hit
            blob = local_raw / f"p{pass_no}_{idx}.bin"
            if not blob.is_file():
                continue
            data = blob.read_bytes()
            # trim to the map range (dd is page aligned)
            page_start = start & ~4095
            trim = start - page_start
            data = data[trim : trim + (end - start)]
            entry_name, entry_off, entry_size = libs[lib]
            disk_path = args.out / "disk" / lib
            if not disk_path.is_file():
                with zipfile.ZipFile(split_apk) as zf:
                    disk_path.parent.mkdir(parents=True, exist_ok=True)
                    disk_path.write_bytes(zf.read(entry_name))
            disk = disk_path.read_bytes()
            buf = covered.get(lib)
            if buf is None:
                buf = bytearray(b"\x00" * len(disk))
                covered[lib] = buf
                mask[lib] = bytearray(len(disk))
            buf[mem_off : mem_off + len(data)] = data
            mask[lib][mem_off : mem_off + len(data)] = b"\x01" * len(data)
            diffs[lib] = count_covered_diff(bytes(buf), disk, mask[lib])
        report["passes"][str(pass_no)] = {
            "maps": len(rows),
            "libs": sorted(covered),
            "diffBytes": diffs,
        }
        for lib, buf in covered.items():
            prev = best.get(lib)
            score = diffs.get(lib, 0)
            if prev is None or score > prev[0]:
                best[lib] = (score, buf, pass_no)
                masks[lib] = bytes(mask[lib])

    for lib, (score, buf, pass_no) in sorted(best.items()):
        disk = (args.out / "disk" / lib).read_bytes()
        mk = masks.get(lib, b"\x01" * len(disk))
        rs = covered_diff_ranges(bytes(buf), disk, mk)
        rx_off, rx_size = elf_rx_file_range(disk)
        in_rx = [(s, e) for s, e in rs if s < rx_off + rx_size and e > rx_off]
        info = {
            "pass": pass_no,
            "diskSha1": sha1(disk),
            "memSha1": sha1(bytes(buf)),
            "diffBytes": sum(e - s for s, e in rs),
            "diffRanges": len(rs),
            "diffInRx": sum(e - s for s, e in in_rx),
            "firstDiff": hex(rs[0][0]) if rs else None,
            "lastDiff": hex(rs[-1][1]) if rs else None,
            "rxOffset": hex(rx_off),
            "rxSize": hex(rx_size),
        }
        report["libs"][lib] = info
        if score > 0:
            (args.out / f"{lib}.mem.bin").write_bytes(bytes(buf))
        print(
            f"{lib:<40} pass={pass_no} diff={info['diffBytes']:>8} "
            f"ranges={info['diffRanges']:>4} first={info['firstDiff']} "
            f"rx={info['rxOffset']}+{info['rxSize']}"
        )

    (args.out / "report.json").write_text(
        json.dumps(report, indent=2) + "\n", encoding="utf-8"
    )
    print(f"report -> {args.out / 'report.json'}")
    return 0


if __name__ == "__main__":
    try:
        raise SystemExit(main())
    except Exception as exc:  # noqa: BLE001 - CLI
        print(f"error: {exc}", file=sys.stderr)
        raise SystemExit(1)
